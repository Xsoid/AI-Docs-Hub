from __future__ import annotations

import subprocess
import tempfile
import unittest
from importlib.machinery import SourceFileLoader
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SCRIPT = ROOT / "scripts" / "generate-hub-pages"
MODULE = SourceFileLoader("generate_hub_pages", str(SCRIPT)).load_module()


class HubPagesTests(unittest.TestCase):
    def test_canonical_docs_generate_marked_starlight_pages(self) -> None:
        result = subprocess.run(["python3.11", str(SCRIPT)], cwd=ROOT, capture_output=True, text=True, check=False)
        self.assertEqual(result.returncode, 0, result.stderr)
        page = ROOT / "docs-site/src/content/docs/hub/gui-dashboard.md"
        rendered = page.read_text(encoding="utf-8")
        self.assertIn("<!-- Generated by scripts/generate-hub-pages. Do not edit manually. -->", rendered)
        self.assertIn("В footer status dashboard", rendered)

    def test_llms_generation_refreshes_canonical_hub_pages(self) -> None:
        result = subprocess.run(["python3.11", str(ROOT / "scripts" / "generate-llms")], cwd=ROOT, capture_output=True, text=True, check=False)
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn("Generated by scripts/generate-hub-pages", (ROOT / "docs-site/src/content/docs/standards/generated-artifacts.md").read_text(encoding="utf-8"))

    def test_generated_pages_are_ignored_and_stale_marked_page_is_removed(self) -> None:
        source = ROOT / "docs/operations/example-new-page.md"
        generated = ROOT / "docs-site/src/content/docs/hub/example-new-page.md"
        try:
            source.write_text("# Example New Page\n\nFixture content.\n", encoding="utf-8")
            created = subprocess.run(["python3.11", str(SCRIPT)], cwd=ROOT, capture_output=True, text=True, check=False)
            self.assertEqual(created.returncode, 0, created.stderr)
            self.assertIn(MODULE.MARKER, generated.read_text(encoding="utf-8"))
            result = subprocess.run(["git", "check-ignore", "-q", str(generated.relative_to(ROOT))], cwd=ROOT, check=False)
            self.assertEqual(result.returncode, 0)
        finally:
            source.unlink(missing_ok=True)
            subprocess.run(["python3.11", str(SCRIPT)], cwd=ROOT, capture_output=True, text=True, check=False)
            generated.unlink(missing_ok=True)

    def test_removes_only_stale_marked_page(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            source = root / "docs/operations/current.md"
            output = root / "site/hub/current.md"
            stale = root / "site/hub/obsolete.md"
            hand_authored = root / "site/hub/overview.md"
            source.parent.mkdir(parents=True)
            output.parent.mkdir(parents=True)
            source.write_text("# Current\n", encoding="utf-8")
            stale.write_text(MODULE.MARKER + "\n", encoding="utf-8")
            hand_authored.write_text("# Overview\n", encoding="utf-8")
            original_site, original_dirs = MODULE.SITE, MODULE.MANAGED_DIRECTORIES
            try:
                MODULE.SITE = root / "site"
                MODULE.MANAGED_DIRECTORIES = (root / "site/hub", root / "site/standards")
                MODULE.validate_mapping({source: output})
                for path in MODULE.stale_outputs({source: output}):
                    path.unlink()
            finally:
                MODULE.SITE, MODULE.MANAGED_DIRECTORIES = original_site, original_dirs
            self.assertFalse(stale.exists())
            self.assertTrue(hand_authored.exists())

    def test_refuses_collision_and_non_generated_overwrite(self) -> None:
        source_a = ROOT / "docs/operations/codebase-memory.md"
        source_b = ROOT / "docs/operations/command-reference.md"
        output = ROOT / "docs-site/src/content/docs/hub/collision-test.md"
        original_sources = MODULE.sources
        try:
            MODULE.sources = lambda: {source_a: output, source_b: output}
            with self.assertRaisesRegex(ValueError, "collision"):
                MODULE.generate()
            MODULE.sources = lambda: {source_a: output}
            output.write_text("# Hand authored\n", encoding="utf-8")
            with self.assertRaisesRegex(ValueError, "non-generated"):
                MODULE.generate()
        finally:
            MODULE.sources = original_sources
            output.unlink(missing_ok=True)

    def test_docs_check_fails_for_stale_generated_output(self) -> None:
        output = ROOT / "docs-site/src/content/docs/hub/architecture.md"
        original = output.read_text(encoding="utf-8")
        try:
            output.write_text(original + "stale fixture\n", encoding="utf-8")
            result = subprocess.run(["make", "docs-check"], cwd=ROOT, capture_output=True, text=True, check=False)
            self.assertNotEqual(result.returncode, 0)
            self.assertIn("generated page is missing or stale", result.stderr)
        finally:
            output.write_text(original, encoding="utf-8")


if __name__ == "__main__":
    unittest.main()
